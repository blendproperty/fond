import {test,expect} from '@playwright/test';

test('dine-in checkout sends plated order with arrival time and tracks table service',async({page},info)=>{
 await page.clock.setFixedTime(new Date('2026-10-21T09:00:00+02:00'));
 await page.route('**/api/store',async route=>{const response=await route.fetch(),body=await response.json();body.open=true;body.settings.enforceHours=false;await route.fulfill({response,json:body});});
 await page.goto('/');
 await page.getByRole('button',{name:'Dine in',exact:true}).click();
 await expect(page.getByText('Dine in at FOND · plated and served at your table')).toBeVisible();
 expect(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth)).toBe(true);
 await page.getByRole('button',{name:'Add Smashed Avo',exact:true}).click();
 await page.getByRole('button',{name:/^Basket/}).click();
 await expect(page.getByRole('tab',{name:'Dine in'})).toHaveAttribute('aria-selected','true');
 const arrival=page.getByLabel('Expected arrival time (today)');
 await expect(arrival).toBeEnabled();
 await expect(page.getByLabel('Business and building')).toHaveCount(0);
 await page.getByLabel('Your name').fill('Dine-in fixture');
 await page.getByLabel('Contact number',{exact:true}).fill('0821234567');
 await page.getByLabel('Email me when my order is received and ready').uncheck();
 await page.getByRole('dialog').screenshot({path:info.outputPath('dine-in-basket.png')});
 const responsePromise=page.waitForResponse(r=>r.url().endsWith('/api/orders')&&r.request().method()==='POST');
 await page.getByRole('button',{name:'Send order to FOND'}).click();
 const response=await responsePromise;
 expect(response.status()).toBe(201);
 const body=await response.json();
 expect(response.request().postDataJSON().fulfillment).toBe('dine_in');
 const lookup=await page.request.get(`/api/orders?reference=${body.reference}`);
 expect((await lookup.json()).fulfillment).toBe('dine_in');
 await expect(page.getByText('Order sent to FOND.')).toBeVisible();
 await expect(page.getByText(/Your order will be plated for table service/)).toBeVisible();
 await page.getByRole('button',{name:'Back to the menu'}).click();
 await page.route('**/api/orders?reference=*',route=>route.fulfill({json:{...body,fulfillment:'dine_in',status:'ready',collectionTime:'ASAP',estimatedPrepMinutes:10}}));
 await page.getByRole('button',{name:'Track order'}).click();
 await expect(page.getByText('Ready for table service',{exact:true})).toBeVisible();
 await expect(page.getByText(/Please tell staff when you arrive/)).toBeVisible();
});

test('kitchen ticket instructs plating and staff can mark the paid order served',async({page,request},info)=>{
 const created=await request.post('/api/orders',{headers:{'Idempotency-Key':crypto.randomUUID()},data:{customerName:'Dine-in kitchen fixture',contactNumber:'0821234567',collectionTime:'ASAP',fulfillment:'dine_in',note:'Table 4',lines:[{id:'espresso-single',quantity:1}]}});
 expect(created.status()).toBe(201);
 const {displayReference,reference}=await created.json();
 await page.goto('/staff');
 await page.getByLabel('Staff access code').fill(process.env.FOND_STAFF_CODE!);
 await page.getByRole('button',{name:'Open order queue'}).click();
 const card=page.locator('.staff-card').filter({hasText:displayReference});
 await expect(card.getByText('DINE IN · PLATED',{exact:true})).toBeVisible();
 await expect(card.getByText('Plate and serve at the table — do not pack',{exact:true})).toBeVisible();
 await expect(card.getByText('Table 4',{exact:true})).toBeVisible();
 await card.getByRole('button',{name:'Accept order'}).click();
 await card.getByRole('button',{name:'Record Yoco entry'}).click();
 const posDialog=page.getByRole('dialog',{name:'Confirm Yoco POS entry'});
 await posDialog.getByLabel('Yoco POS receipt / order number').fill(`DINE-${reference}`);
 await posDialog.getByRole('button',{name:'Confirm POS entry'}).click();
 await card.getByRole('button',{name:'Start preparing'}).click();
 await card.getByRole('button',{name:'Ready for table service'}).click();
 await expect(card.getByRole('button',{name:'Mark served'})).toHaveCount(0);
 await card.getByRole('button',{name:'Take payment'}).click();
 const paymentDialog=page.getByRole('dialog',{name:'Record payment received'});
 await paymentDialog.getByLabel('Cash',{exact:true}).check();
 await paymentDialog.getByRole('button',{name:'Confirm payment received'}).click();
 await card.screenshot({path:info.outputPath('dine-in-kitchen.png')});
 await card.getByRole('button',{name:'Mark served'}).click();
 await expect(card).toHaveCount(0);
 expect((await (await request.get(`/api/orders?reference=${reference}`)).json()).status).toBe('completed');
});
